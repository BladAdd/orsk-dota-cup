-- =====================================================================
-- Расписание: первый раунд стартует сегодня, остальные раунды сдвинуты.
--
-- Зачем. 003_seed.sql ставил первый раунд на 28 ноября, а сам турнир в
-- public.tournaments числился как 22 ноября 07:00–18:10. Из-за расхождения
-- на сайте одновременно жили два противоречащих факта: отсчёт «турнир идёт»
-- на главной и матчи через неделю в сетке и расписании.
--
-- Теперь всё сходится: раунд 1 — сегодня, 22 ноября, с 15:00 по местному
-- (UTC+5), каждый следующий раунд на своём дне. Сдвиг ровно на шесть дней
-- относительно сида, ритм турнира сохранён.
--
-- Заодно правится распределение призового фонда: в живой базе лежало
-- 15 000 / 0 / 0, из-за чего страница «Призовые» показывала 0 ₽ за второе
-- и третье место, хотя регламент и новости обещают 9 000 / 4 000 / 2 000.
--
-- Повторный запуск безопасен: все изменения — это UPDATE абсолютных значений.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Окно турнира: регистрация закрывается до старта
-- ---------------------------------------------------------------------
update public.tournaments
   set registration_closes = '2026-11-21 23:59:00+05',
       starts_at           = '2026-11-22 15:00:00+05',
       ends_at             = '2026-11-30 23:00:00+05',
       status              = 'live'
 where id = '90000000-0000-4000-8000-000000000001';

-- ---------------------------------------------------------------------
-- 2. Призовые: 9 000 / 4 000 / 2 000 (как в регламенте, п. 8.1)
-- ---------------------------------------------------------------------
insert into public.settings (key, value, is_public)
values ('prize', jsonb_build_object(
  'total', 15000,
  'split', jsonb_build_array(
     jsonb_build_object('place', 1, 'amount', 9000),
     jsonb_build_object('place', 2, 'amount', 4000),
     jsonb_build_object('place', 3, 'amount', 2000))), true)
on conflict (key) do update set value = excluded.value, is_public = true;

-- ---------------------------------------------------------------------
-- 3. Сетка: раунд 1 — сегодня, дальше по дням
--    Время местное (UTC+5), поэтому +05 в каждой отметке.
-- ---------------------------------------------------------------------
update public.bracket_matches set scheduled_at = v.when_at
from (values
  -- Раунд 1 (BO1), 22 ноября, каждый час с 15:00
  ('aaaaaaaa-0000-4000-8000-000000000101'::uuid, '2026-11-22 15:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000102'::uuid, '2026-11-22 16:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000103'::uuid, '2026-11-22 17:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000104'::uuid, '2026-11-22 18:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000105'::uuid, '2026-11-22 19:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000106'::uuid, '2026-11-22 20:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000107'::uuid, '2026-11-22 21:00:00+05'::timestamptz),
  -- Четвертьфиналы (BO1), 23 ноября; у четвёртого матча времени нет — это бай
  ('aaaaaaaa-0000-4000-8000-000000000201'::uuid, '2026-11-23 16:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000202'::uuid, '2026-11-23 17:30:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000203'::uuid, '2026-11-23 19:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000204'::uuid, null),
  -- Полуфиналы (BO3), 29 ноября
  ('aaaaaaaa-0000-4000-8000-000000000301'::uuid, '2026-11-29 15:00:00+05'::timestamptz),
  ('aaaaaaaa-0000-4000-8000-000000000302'::uuid, '2026-11-29 18:00:00+05'::timestamptz),
  -- Финал (BO5), 30 ноября
  ('aaaaaaaa-0000-4000-8000-000000000401'::uuid, '2026-11-30 17:00:00+05'::timestamptz)
) as v(id, when_at)
where public.bracket_matches.id = v.id;

